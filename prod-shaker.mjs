import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const p = await (await b.newContext({ viewport: { width: 1280, height: 900 }, colorScheme: 'dark' })).newPage();
const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.addInitScript(() => { try { localStorage.setItem('nl-theme', 'dark'); } catch {} });
await p.goto('https://nutrilab-seven.vercel.app/shaker', { waitUntil: 'networkidle' });
const a = p.getByRole('button', { name: /aceitar/i }); if (await a.count()) await a.first().click().catch(() => {});
await p.getByRole('button', { name: 'Ganhar massa' }).click();
await p.getByRole('button', { name: /^Misturar!$/ }).click();
await p.waitForTimeout(2600);
console.log('legenda do shaker:', (await p.locator('aside ul li').allTextContents()).map(s => s.replace(/\s+/g, ' ').trim()));
console.log('status:', (await p.locator('aside p[aria-live]').textContent()).trim());
await p.getByRole('button', { name: /Adicionar ao carrinho/ }).click();
await p.waitForTimeout(800);
const cart = JSON.parse(await p.evaluate(() => localStorage.getItem('nl_cart_v1') || '[]'));
console.log('carrinho:', cart.map(i => `${i.name} (${(i.priceCents / 100).toFixed(2)})`));
console.log('erros de página:', errs.length ? errs : 'nenhum');
await p.screenshot({ path: 'prod-shaker.png' });
await b.close();
